-- =====================================================================
-- 000 — Base schema: the tables FaithSync started from
--
-- Run FIRST on a new, empty Supabase project, then db/001 … in order.
-- Wrapped in a transaction: if any line fails, nothing is applied.
-- Do NOT run this on the live database — it already has these tables.
--
-- These were first made by hand in the Supabase dashboard, before the
-- numbered files existed, so no file created them. This file records them
-- as they were before db/001, taken from the live database (October 2026)
-- minus the columns, rules and indexes the later files add themselves
-- (e.g. events.venue → db/043, members.profile_id → db/014). Running
-- 000 → the last file on an empty project gives the same database.
--
-- Left out on purpose: three early tables nobody used and their four
-- notification triggers (notifications, proposals, fund_categories) —
-- db/067 removed them from the live database because the notification
-- feed showed finance amounts and member names to every level and branch.
--
--   churches            the branches
--   profiles            one per login (auth.users); level and branch
--   members             the congregation records (a member may have a login)
--   ministries, ministry_assignments
--   events, transactions
--   discipleship_modules / _questions / _progress, module_handouts
--   bible_verses, chatbot_documents
--   get_my_role(), get_my_church_id()   used by every access rule
--   handle_new_user + on_auth_user_created   a profile for each new login
--   storage bucket 'handouts'           training handout files (private)
--
-- Access rules: every table has row level security on. The rules below
-- are the ones no later file rewrites; db/001 onwards add the rest.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- Branches and logins
-- ---------------------------------------------------------------------
create table if not exists public.churches (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  location   text,
  created_at timestamptz default now(),
  constraint churches_name_unique unique (name)
);

create table if not exists public.profiles (
  id        uuid primary key references auth.users (id) on delete cascade,
  email     text unique,
  role      text default 'member',   -- allowed levels: db/004, db/050
  full_name text,
  church_id uuid references public.churches (id)
);

-- The caller's level and branch. db/013 adds "and not disabled".
create or replace function public.get_my_role()
returns text
language sql
stable
security definer
set search_path = public
as $$ select role from profiles where id = auth.uid(); $$;

create or replace function public.get_my_church_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$ select church_id from profiles where id = auth.uid(); $$;

-- ---------------------------------------------------------------------
-- Congregation
-- ---------------------------------------------------------------------
create table if not exists public.members (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  full_name  text,
  role       text,
  ministry   text,   -- old free-text ministry; db/022 moves it to ministry_assignments
  status     text,
  phone      text,
  church_id  uuid default public.get_my_church_id() references public.churches (id)
);

create table if not exists public.ministries (
  id               uuid primary key default gen_random_uuid(),
  name             text not null,
  description      text,
  leader_id        uuid references public.profiles (id),
  meeting_schedule text,
  color_code       text default '#3b82f6'
);

create table if not exists public.ministry_assignments (
  id          uuid primary key default gen_random_uuid(),
  ministry_id uuid not null references public.ministries (id),
  member_id   bigint not null references public.members (id),
  church_id   uuid not null references public.churches (id),
  role        text default 'member' check (role in ('leader', 'member')),
  assigned_at timestamptz default now(),
  assigned_by uuid references public.profiles (id),
  constraint ministry_assignments_ministry_id_member_id_church_id_key unique (ministry_id, member_id, church_id)
);

-- ---------------------------------------------------------------------
-- Events and finance
-- ---------------------------------------------------------------------
create table if not exists public.events (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  title       text,
  ministry    text,
  date        date,
  budget      numeric,   -- no longer used by the app (removed from events in Oct 2026)
  status      text,      -- allowed values: db/051
  description text,
  church_id   uuid references public.churches (id),
  created_by  uuid default auth.uid() references public.profiles (id),
  approved_by uuid references public.profiles (id),
  constraint "Events_pkey" primary key (id)
);

create table if not exists public.transactions (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz default now(),
  date_recorded date default current_date,
  type          text check (type in ('income', 'expense')),
  amount        numeric(12,2) not null,
  description   text,
  recorded_by   uuid default auth.uid() references auth.users (id),
  category      text default 'Tithe',
  fund          text,
  member        text,              -- the giver / payee, as typed
  status        text default 'Verified',
  notes         text,
  date          date,
  church_id     uuid references public.churches (id)
);

-- ---------------------------------------------------------------------
-- Training (discipleship)
-- ---------------------------------------------------------------------
create table if not exists public.discipleship_modules (
  id          bigint generated always as identity primary key,
  created_at  timestamptz default now(),
  title       text not null,
  description text,
  order_index integer not null default 0,
  is_active   boolean default true
);

create table if not exists public.discipleship_questions (
  id          bigint generated always as identity primary key,
  module_id   bigint references public.discipleship_modules (id) on delete cascade,
  question    text not null,
  order_index integer not null default 0
);

create table if not exists public.discipleship_progress (
  id          bigint generated always as identity primary key,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now(),
  member_id   uuid references auth.users (id) on delete cascade,   -- the member's login
  module_id   bigint references public.discipleship_modules (id) on delete cascade,
  question_id bigint references public.discipleship_questions (id) on delete cascade,
  answer      text,
  status      text default 'pending',
  reviewed_by text,
  reviewed_at timestamptz,
  notes       text,
  church_id   uuid references public.churches (id),
  constraint discipleship_progress_member_id_question_id_key unique (member_id, question_id)
);

create table if not exists public.module_handouts (
  id          bigint generated always as identity primary key,
  created_at  timestamptz default now(),
  module_id   bigint references public.discipleship_modules (id) on delete cascade,
  file_name   text not null,
  file_path   text not null,
  file_size   bigint,
  uploaded_by text,
  description text
);

-- ---------------------------------------------------------------------
-- Content: verse of the day and the assistant's documents
-- ---------------------------------------------------------------------
create table if not exists public.bible_verses (
  id         bigint generated always as identity primary key,
  reference  text not null,
  verse_text text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.chatbot_documents (
  id         uuid primary key default gen_random_uuid(),
  church_id  uuid references public.churches (id),
  title      text not null,
  content    text not null,
  doc_type   text default 'general',
  is_active  boolean not null default true,
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- A profile for every new login. db/015 replaces the function (saves
-- the email too); the trigger stays.
-- ---------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------
-- Row level security on every table
-- ---------------------------------------------------------------------
alter table public.churches               enable row level security;
alter table public.profiles               enable row level security;
alter table public.members                enable row level security;
alter table public.ministries             enable row level security;
alter table public.ministry_assignments   enable row level security;
alter table public.events                 enable row level security;
alter table public.transactions           enable row level security;
alter table public.discipleship_modules   enable row level security;
alter table public.discipleship_questions enable row level security;
alter table public.discipleship_progress  enable row level security;
alter table public.module_handouts        enable row level security;
alter table public.bible_verses           enable row level security;
alter table public.chatbot_documents      enable row level security;

-- ---------------------------------------------------------------------
-- The access rules no later file rewrites (as in the live database).
-- Note: the verse, module and question read rules are open to
-- "public" (also signed-out visitors); see the Security notes in
-- docs/SYSTEM.md.
-- ---------------------------------------------------------------------
drop policy if exists "Anyone authenticated can read churches" on public.churches;
create policy "Anyone authenticated can read churches"
  on public.churches for select to authenticated
  using (true);

drop policy if exists "Only admins manage churches" on public.churches;
create policy "Only admins manage churches"
  on public.churches for all to authenticated
  using (public.get_my_role() = 'admin')
  with check (public.get_my_role() = 'admin');

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
  on public.profiles for select to public
  using (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
  on public.profiles for update to public
  using (auth.uid() = id);

drop policy if exists "Public read access" on public.bible_verses;
create policy "Public read access"
  on public.bible_verses for select to public
  using (true);

drop policy if exists "Members can view modules" on public.discipleship_modules;
create policy "Members can view modules"
  on public.discipleship_modules for select to public
  using (true);

drop policy if exists "Members can view questions" on public.discipleship_questions;
create policy "Members can view questions"
  on public.discipleship_questions for select to public
  using (true);

drop policy if exists "Members can view own progress" on public.discipleship_progress;
create policy "Members can view own progress"
  on public.discipleship_progress for select to public
  using (auth.uid() = member_id);

drop policy if exists "leader admin view progress scoped" on public.discipleship_progress;
create policy "leader admin view progress scoped"
  on public.discipleship_progress for select to public
  using (
    public.get_my_role() in ('admin', 'pastor')
    or (public.get_my_role() = 'leader' and church_id = public.get_my_church_id())
  );

drop policy if exists "Authenticated users can view handouts" on public.module_handouts;
create policy "Authenticated users can view handouts"
  on public.module_handouts for select to public
  using (auth.role() = 'authenticated');

-- ---------------------------------------------------------------------
-- Training handout files: a private storage bucket. Upload and delete
-- rules come in db/025.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('handouts', 'handouts', false)
on conflict (id) do nothing;

drop policy if exists "Authenticated users can read handouts" on storage.objects;
create policy "Authenticated users can read handouts"
  on storage.objects for select to public
  using (bucket_id = 'handouts' and auth.role() = 'authenticated');

commit;

